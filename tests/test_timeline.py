"""Tests for the logic in the timeline scripts that does not need DaVinci Resolve.

Run from the repo root (needs FFmpeg on PATH):
    uvx --with pytest pytest -q tests

Test clips are generated by FFmpeg in a temporary folder; no real footage is used.
"""
import importlib.util

import random
import shutil
from array import array
import subprocess
import wave
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
FFMPEG = shutil.which('ffmpeg')
needs_ffmpeg = pytest.mark.skipif(not FFMPEG or not shutil.which('ffprobe'), reason='FFmpeg not installed')


def load(name):
    spec = importlib.util.spec_from_file_location(name.replace(' ', '_'), ROOT / (name + '.py'))
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


@pytest.fixture(scope='module')
def yt():
    return load('YouTube Timeline')


@pytest.fixture(scope='module')
def reels():
    return load('Reels Timeline')


def test_scripts_differ_only_in_workflow():
    youtube = (ROOT / 'YouTube Timeline.py').read_text(encoding='utf-8').splitlines()
    vertical = (ROOT / 'Reels Timeline.py').read_text(encoding='utf-8').splitlines()
    assert len(youtube) == len(vertical)
    differences = [(a, b) for a, b in zip(youtube, vertical, strict=True) if a != b]
    assert differences == [("WORKFLOW = 'YouTube'", "WORKFLOW = 'Reels'")]


# --- frame rates -----------------------------------------------------------

@pytest.mark.parametrize('stream, expected', [
    ({'r_frame_rate': '25/1', 'avg_frame_rate': '25/1'}, 25.0),
    ({'r_frame_rate': '30000/1001', 'avg_frame_rate': '30000/1001'}, 29.97),
    ({'r_frame_rate': '2987/100', 'avg_frame_rate': '2987/100'}, 29.97),   # phone VFR average
    ({'r_frame_rate': '90000/1', 'avg_frame_rate': '25/1'}, 25.0),         # bogus VFR r_frame_rate
    ({'r_frame_rate': '120/1', 'avg_frame_rate': '120/1'}, 60.0),          # high speed: never faster than 60
    ({'r_frame_rate': '15/1', 'avg_frame_rate': '15/1'}, 23.976),          # timelapse: lowest supported
    ({'r_frame_rate': '0/0', 'avg_frame_rate': '0/0', 'nb_frames': '500', 'duration': '20'}, 25.0),
])
def test_source_frame_rate(yt, stream, expected):
    assert yt.source_frame_rate(stream) == expected


def test_timeline_uses_lowest_source_rate(yt):
    rows = [{'source_fps': 50.0}, {'source_fps': 25.0}, {'source_fps': 29.97}]
    assert yt.timeline_frame_rate(rows) == 25.0


def test_invalid_timeline_fps_setting_is_refused(yt, monkeypatch):
    monkeypatch.setattr(yt, 'TIMELINE_FPS', 27)
    with pytest.raises(RuntimeError):
        yt.timeline_frame_rate([{'source_fps': 25.0}])


def test_frame_rate_warnings(yt):
    rows = [{'source_fps': 25.0}, {'source_fps': 50.0}, {'source_fps': 29.97}, {'source_fps': 29.97}]
    warnings = yt.frame_rate_warnings(rows, 25.0)
    assert len(warnings) == 1 and warnings[0].startswith('2 clip(s) recorded at 29.97 fps')
    assert yt.frame_rate_warnings([{'source_fps': 59.94}], 29.97) == []


# --- timestamps ------------------------------------------------------------

def test_parse_time(yt):
    assert yt.parse_time('2026-10-01T10:00:00Z') == yt.parse_time('2026-10-01T12:00:00+0200')
    assert yt.parse_time('2026-10-01T10:00:00') is None   # no time zone: not comparable
    assert yt.parse_time('1904-01-01T00:00:00Z') is None  # empty QuickTime date
    assert yt.parse_time('') is None


# --- audio matching ---------------------------------------------------------

def test_match_envelopes_finds_known_lag(yt):
    rng = random.Random(1)
    reference = [rng.random() for _ in range(1200)]          # 120 s at 10 Hz
    source = reference[300:700]                              # starts 30 s into the reference
    score, lag, overlap = yt.match_envelopes(source, reference, min_overlap=20)
    assert score > .99
    assert lag == pytest.approx(-30.0)
    assert overlap == pytest.approx(40.0)


def test_match_envelopes_rejects_too_little_overlap(yt):
    assert yt.match_envelopes([1.0] * 50, [1.0] * 1000, min_overlap=35) is None


# --- track layout ----------------------------------------------------------

def test_simultaneous_clips_of_one_camera_get_an_extra_track(yt):
    def row(camera, start, duration, phone=False, reference=False):
        return {'camera': camera, 'sort_time': start, 'duration': duration, 'path': camera + str(start),
                'is_phone': phone, 'reference_audio': reference, 'audio_rank': 0 if reference else 1}
    rows = [row('Sony', 0, 60, reference=True), row('Sony', 30, 60, reference=True),
            row('iPhone', 0, 60, phone=True)]
    labels = yt.allocate_tracks(rows, 25.0)
    assert sorted(labels.values()) == ['Sony', 'Sony — overlap 2', 'iPhone']
    assert len({r['track_index'] for r in rows}) == 3
    # The phone sits above the reference camera (higher video track number).
    assert rows[2]['track_index'] > rows[0]['track_index']


# --- folder scanning --------------------------------------------------------

def test_select_media_paths_skips_proxies_hidden_files_and_links(yt, tmp_path):
    (tmp_path / 'A').mkdir()
    (tmp_path / 'A' / 'clip1.mp4').write_bytes(b'original')
    (tmp_path / 'A' / 'Proxy').mkdir()
    (tmp_path / 'A' / 'Proxy' / 'clip1.mp4').write_bytes(b'proxy of clip1')
    (tmp_path / 'A' / 'Proxy' / 'orphan.mp4').write_bytes(b'proxy without original')
    (tmp_path / 'A' / '._clip1.mp4').write_bytes(b'macOS resource fork')
    (tmp_path / 'A' / 'notes.txt').write_text('not a video')
    outside = tmp_path.parent / (tmp_path.name + '-outside')
    outside.mkdir()
    (outside / 'elsewhere.mp4').write_bytes(b'should not be followed')
    (tmp_path / 'link').symlink_to(outside, target_is_directory=True)
    found = yt.select_media_paths(tmp_path)
    names = sorted(p.name for p in found)
    assert names == ['clip1.mp4', 'orphan.mp4']
    assert found.ignored == 2


# --- real clips (FFmpeg) ------------------------------------------------------

def make_clip(path, width, height, fps, seconds, audio=None, created=None, rotation=None, audio_codec='aac'):
    command = [FFMPEG, '-v', 'error', '-y']
    if rotation is not None:
        command += ['-display_rotation', str(rotation)]
    command += ['-f', 'lavfi', '-i', 'color=c=gray:s=%dx%d:r=%s:d=%s' % (width, height, fps, seconds)]
    if audio:
        command += ['-i', str(audio), '-shortest', '-c:a', audio_codec]
    command += ['-c:v', 'libx264', '-preset', 'ultrafast', '-pix_fmt', 'yuv420p']
    if created:
        command += ['-metadata', 'creation_time=' + created]
    command.append(str(path))
    subprocess.run(command, check=True)
    return path


def write_wav(path, samples, rate=8000):
    with wave.open(str(path), 'wb') as handle:
        handle.setnchannels(1)
        handle.setsampwidth(2)
        handle.setframerate(rate)
        handle.writeframes(array('h', (int(max(-1, min(1, s)) * 32000) for s in samples)).tobytes())
    return path


@needs_ffmpeg
def test_inspect_orientation_and_workflow_filters(yt, reels, tmp_path):
    ffprobe, _ = yt.binaries()
    landscape = make_clip(tmp_path / 'landscape.mp4', 320, 180, 25, 2)
    portrait = make_clip(tmp_path / 'portrait.mp4', 180, 320, 25, 2)
    rotated = make_clip(tmp_path / 'rotated.mp4', 320, 180, 25, 2, rotation=90)
    square = make_clip(tmp_path / 'square.mp4', 200, 200, 25, 2)
    row, reason = yt.inspect(landscape, ffprobe)
    assert reason is None and row['orientation'] == 'landscape' and row['source_fps'] == 25.0
    assert yt.inspect(portrait, ffprobe)[0] is None          # YouTube skips portrait
    assert yt.inspect(rotated, ffprobe)[0] is None           # stored landscape, displayed portrait
    assert reels.inspect(rotated, ffprobe)[0]['orientation'] == 'portrait'
    assert reels.inspect(landscape, ffprobe)[0]['orientation'] == 'landscape'
    assert yt.inspect(square, ffprobe) == (None, 'square video')


@needs_ffmpeg
def test_sony_sidecar_is_used_only_when_it_matches(yt, tmp_path):
    ffprobe, _ = yt.binaries()
    clip = make_clip(tmp_path / 'C0001.MP4', 320, 180, 25, 2, created='2026-10-01T10:00:00Z')
    def sidecar(frames, maker='Sony'):
        (tmp_path / 'C0001M01.XML').write_text(
            '<?xml version="1.0"?><NonRealTimeMeta xmlns="urn:schemas-professionalDisc:nonRealTimeMeta:ver.2.00">'
            '<Duration value="%d"/><CreationDate value="2026-10-01T12:00:00+02:00"/>'
            '<Device manufacturer="%s" modelName="ILCE-7M4" serialNo="1234"/>'
            '<AcquisitionRecord><Group name="CameraUnitMetadataSet">'
            '<Item name="CaptureGammaEquation" value="s-log3-cine"/>'
            '<Item name="CaptureColorPrimaries" value="s-gamut3-cine"/></Group></AcquisitionRecord>'
            '</NonRealTimeMeta>' % (frames, maker))
    sidecar(50)
    row, _ = yt.inspect(clip, ffprobe)
    assert row['camera'] == 'Sony ILCE-7M4 #1234'
    assert row['profile'] == 'S-Gamut3.Cine/S-Log3'
    sidecar(999)                                             # describes another recording
    assert yt.inspect(clip, ffprobe)[0]['profile'] is None
    sidecar(50, maker='Other')                               # not a Sony file
    assert yt.inspect(clip, ffprobe)[0]['profile'] is None


@needs_ffmpeg
@pytest.mark.parametrize('audio_codec, rate', [
    ('pcm_s16le', 8000),   # uncompressed, as most dedicated cameras record
    ('aac', 48000),        # compressed, as phones record
])
def test_audio_sync_corrects_a_wrong_camera_clock(yt, tmp_path, audio_codec, rate):
    """Camera B's clock is 37 s fast; its two clips must land where the sound matches."""
    rng = random.Random(7)
    envelope = []
    while len(envelope) < 130 * 10:
        envelope.extend([rng.choice((.05, .3, .9))] * rng.randint(2, 12))
    # Broadband noise with a random loudness pattern, like speech in a room.
    samples = [envelope[i * 10 // rate] * rng.uniform(-1, 1) for i in range(130 * rate)]
    full = write_wav(tmp_path / 'full.wav', samples, rate)
    def piece(name, start, seconds):
        return write_wav(tmp_path / name, samples[start * rate:(start + seconds) * rate], rate)
    (tmp_path / 'A').mkdir()
    (tmp_path / 'B').mkdir()
    # AAC adds an encoder delay of 1024 samples: 21 ms at 48 kHz, under one frame.
    pcm = {'audio_codec': audio_codec}
    make_clip(tmp_path / 'A' / 'ref.mov', 320, 180, 25, 130, full, '2026-10-01T10:00:00Z', **pcm)
    make_clip(tmp_path / 'B' / 'b1.mov', 320, 180, 25, 40, piece('b1.wav', 10, 40), '2026-10-01T10:00:47Z', **pcm)
    make_clip(tmp_path / 'B' / 'b2.mov', 320, 180, 25, 40, piece('b2.wav', 70, 40), '2026-10-01T10:01:47Z', **pcm)
    ffprobe, ffmpeg = yt.binaries()
    rows, excluded = yt.inspect_sources(yt.select_media_paths(tmp_path), ffprobe)
    assert not excluded and len(rows) == 3
    evidence, warnings, reference = yt.sync_audio(rows, ffmpeg)
    by_name = {r['name']: r for r in rows}
    start = by_name['ref.mov']['timestamp']
    assert reference == by_name['ref.mov']['camera']
    assert by_name['b1.mov']['sort_time'] - start == pytest.approx(10.0, abs=.04)   # within one frame
    assert by_name['b2.mov']['sort_time'] - start == pytest.approx(70.0, abs=.04)
    assert by_name['b1.mov']['sync_method'] in yt.CONFIRMED_SYNC
