class FakeClip:
    def __init__(self, uid):
        self.uid = uid

    def GetUniqueId(self):
        return self.uid


class FakeItem:
    def __init__(self, uid, accepts=True):
        self.clip, self.accepts, self.group = FakeClip(uid), accepts, None

    def GetMediaPoolItem(self):
        return self.clip

    def AssignToColorGroup(self, group):
        if self.accepts:
            self.group = group
        return self.accepts


class FakeTimeline:
    def __init__(self, items):
        self.items = items

    def GetItemListInTrack(self, kind, index):
        return self.items if (kind, index) == ('video', 1) else []  # may be None, as Resolve sometimes returns


class FakeProject:
    def __init__(self, refuse=()):
        self.groups, self.refuse = {}, refuse

    def AddColorGroup(self, name):
        if name in self.refuse or name in self.groups:
            return None
        self.groups[name] = 'group ' + name
        return self.groups[name]


