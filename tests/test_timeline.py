    timeline = TrackTimeline([[sony]], {3: [SpanItem('rec-a', 0, 100)], 4: [SpanItem('rec-b', 0, 100), SpanItem('rec-gap', 200, 250)]})
    recorders = [{'key': 'a', 'audio_track_index': 3, 'duration': 4}, {'key': 'b', 'audio_track_index': 4, 'duration': 10}]
