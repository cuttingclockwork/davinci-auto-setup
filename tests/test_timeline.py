# --- sync in other situations (generated clips) ------------------------------

def shared_room(seconds, rate=8000, seed=7):
    """Noise with a random loudness pattern, like speech in a room."""
    rng = random.Random(seed)
    envelope = []
    while len(envelope) < seconds * 10:
        envelope.extend([rng.choice((.05, .3, .9))] * rng.randint(2, 12))
    return [envelope[i * 10 // rate] * rng.uniform(-1, 1) for i in range(seconds * rate)]


def shoot(tmp_path, cameras, rate=8000, seconds=130, seed=7):
    """cameras: {folder: [(file, start, length, clock_error_s, fps, sound), ...]}.

    sound: None = the shared room, a number = a different room (that seed), 'silent' = no audio track.
    """
    room = shared_room(seconds, rate, seed)
    for folder, clips in cameras.items():
        (tmp_path / folder).mkdir(parents=True, exist_ok=True)
        for name, start, length, clock, fps, other_seed in clips:
            wav = None
            if other_seed != 'silent':
                sound = shared_room(seconds, rate, other_seed) if other_seed else room
                wav = write_wav(tmp_path / (name + '.wav'), sound[start * rate:(start + length) * rate], rate)
            created = '2026-10-01T10:%02d:%02dZ' % divmod(start + clock, 60) if 0 <= start + clock < 3600 else None
            if created is None:   # clock errors of hours
                hours, rest = divmod(start + clock, 3600)
                created = '2026-10-01T%02d:%02d:%02dZ' % (10 + hours, rest // 60, rest % 60)
            make_clip(tmp_path / folder / name, 320, 180, fps, length, wav, created, audio_codec='pcm_s16le')
            if wav:
                wav.unlink()   # a loose wav in the folder would count as a recorder
    ffprobe, ffmpeg = yt_module().binaries()
    return ffprobe, ffmpeg


def yt_module():
    return load('YouTube Timeline')


def synced(yt, tmp_path):
    ffprobe, ffmpeg = yt.binaries()
    rows, excluded = yt.inspect_sources(yt.select_media_paths(tmp_path), ffprobe)
    yt.reconcile_missing_camera_metadata(rows)
    evidence, warnings, reference = yt.sync_audio(rows, ffmpeg)
    by_name = {r['name']: r for r in rows}
    return by_name, warnings, excluded


@needs_ffmpeg
def test_single_take_with_a_clock_70_minutes_off_is_synced(yt, tmp_path):
    shoot(tmp_path, {'A': [('ref.mov', 0, 130, 0, 25, None)],
                     'Phone': [('take.mov', 40, 60, -70 * 60, 25, None)]})
    clips, warnings, _ = synced(yt, tmp_path)
    assert clips['take.mov']['sort_time'] - clips['ref.mov']['timestamp'] == pytest.approx(40.0, abs=.04)
    assert any('one sound match' in w for w in warnings)


